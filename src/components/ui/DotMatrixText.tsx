export const DotMatrixText: React.FC<DotMatrixProps> = ({
  text,
  className = '',
  dotSize = 3,
  color = '#0DA5F0',
}) => {
  const chars = text.toUpperCase().split('');

  return (
    <div className={`inline-flex items-center gap-2 select-none ${className}`}>
      {chars.map((char, charIdx) => {
        const matrix = CHAR_MAP[char] || CHAR_MAP[' '];
        return (
          <div key={charIdx} className="flex flex-col gap-[2px]">
            {matrix.map((row, rowIdx) => (
              <div key={rowIdx} className="flex gap-[2px]">
                {row.map((active, colIdx) => (
                  <span
                    key={colIdx}
                    style={{
                      width: `${dotSize}px`,
                      height: `${dotSize}px`,
                      backgroundColor: active ? color : 'rgba(255, 255, 255, 0.08)',
                      boxShadow: active ? `0 0 5px ${color}` : 'none',
                    }}
                    className="rounded-full transition-all duration-300"
                  />
                ))}
              </div>
            ))}
          </div>
        );
      })}
    </div>
  );
};

